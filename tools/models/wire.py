"""Assembles the model wiring and credits from the per-domain fragments in tools/models/wiring/:

- every <domain>.yaml (MiniYaml, tabs) is appended to mods/ww3mod/rules/models-3d.yaml after its header;
- every <domain>-credits.md line goes into CREDITS.md between the "3D models" markers, de-duplicated.

    python tools/models/wire.py
"""

import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RULES = os.path.join(ROOT, "mods", "ww3mod", "rules", "models-3d.yaml")
CREDITS = os.path.join(ROOT, "CREDITS.md")
BEGIN, END = "<!-- 3d-models:begin -->", "<!-- 3d-models:end -->"

HEADER = """# 3D unit models (M4). Each actor that has a glTF model gets WithMeshBody here, merged over its
# definition (this file loads last). The sprite body and turret stay in the rules and stop drawing
# while the mesh is on (WithMeshBody.HidesSprites). Models are built by tools/models/build.py into
# bits/models/; sources and licences: tools/models/units/<name>.py and CREDITS.md.
# Scale is the size over real metres: units are drawn about twice life size, as their sprites were.
# GENERATED by tools/models/wire.py from tools/models/wiring/*.yaml - edit those, not this file.
"""


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read().replace("\r\n", "\n")


def main():
    blocks, keys = [], {}
    for path in sorted(glob.glob(os.path.join(HERE, "wiring", "*.yaml"))):
        text = read(path).strip("\n")
        for key in re.findall(r"^([^\s#][^:]*):\s*$", text, re.M):
            if key in keys:
                raise SystemExit(f"{key} wired twice: {keys[key]} and {os.path.basename(path)}")
            keys[key] = os.path.basename(path)
        blocks.append(f"# --- {os.path.basename(path)} ---\n\n{text}\n")
    with open(RULES, "w", encoding="utf-8", newline="\n") as f:
        # MiniYaml: a blank line between top-level entries keeps them apart.
        f.write(HEADER + "\n" + "\n".join(blocks))

    lines = []
    for path in sorted(glob.glob(os.path.join(HERE, "wiring", "*-credits.md"))):
        for line in read(path).splitlines():
            line = line.strip()
            if line and not line.startswith("#") and line not in lines:
                lines.append(line if line.startswith("- ") else "- " + line)
    credits = read(CREDITS)
    section = (f"{BEGIN}\n### 3D unit models\n\nUnit, vehicle, aircraft and defence models are adapted (cut into parts, "
               "re-textured, weathered) from these works, all under Creative Commons Attribution 4.0 "
               "(https://creativecommons.org/licenses/by/4.0/):\n\n" + "\n".join(lines) + f"\n{END}")
    if BEGIN in credits:
        credits = re.sub(re.escape(BEGIN) + ".*?" + re.escape(END), lambda m: section, credits, flags=re.S)
    else:
        credits = credits.replace("\n## License", "\n" + section + "\n\n## License", 1)
    with open(CREDITS, "w", encoding="utf-8", newline="\n") as f:
        f.write(credits)
    print(f"wired {len(keys)} actors from {len(blocks)} fragments; {len(lines)} credit lines")


if __name__ == "__main__":
    main()
